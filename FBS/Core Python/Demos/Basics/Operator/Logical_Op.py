#1. and 

# Rule: 
    #  if both operands are True then returns True
    #  otherwise return False 

print(True and True)

#2. or  

# Rule: 
    #  if both operands are False then returns False
    #  otherwise return True 

print(False or True)

#3. not 

# Rule:
    #  Opposite of operand

print(not True)

#4. Falsy 

#  Rule:
     # False, None, 0, blank value like : '', []

print('' or 10)

 


    